package collections

// noCopy — структура-маркер нулевого размера, которую распознаёт анализатор
// copylocks из go vet. Встраивание noCopy в тип заставляет go vet сообщать о
// копировании этого типа по значению.
//
// Приём нужен коллекциям [Stack] и [Queue]: копия структуры разделяет с
// оригиналом один и тот же backing array, поэтому две «независимые» на вид
// коллекции начинают незаметно портить данные друг друга. Компилятор такое не
// запрещает, а go vet — предупреждает.
type noCopy struct{}

// Lock — пустая заглушка. Существует только затем, чтобы *noCopy удовлетворял
// интерфейсу sync.Locker: именно по паре методов Lock/Unlock анализатор
// copylocks и опознаёт тип, который нельзя копировать.
func (*noCopy) Lock() {}

// Unlock — пустая заглушка, парная к [noCopy.Lock]; см. комментарий к ней.
func (*noCopy) Unlock() {}
