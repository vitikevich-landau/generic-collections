package main

// ─────────────────────────────────────────────────────────────────────────────
// set.go — МНОЖЕСТВО на дженериках: хранит уникальные значения и быстро
// отвечает «есть такое или нет».
//
// Ключевое отличие от Stack/Queue — ограничение [T comparable], а не [T any].
// Внутри Set это map, а ключ карты в Go ОБЯЗАН быть сравним через == . Поэтому
// тип T без ограничения (any) в ключ поставить нельзя — не скомпилируется.
// comparable как раз и разрешает ==, поэтому именно оно тут и нужно.
//
//	type Set[T comparable] map[T]struct{}
//
// Значение в карте — struct{} (пустая структура): она занимает 0 байт. Нам важен
// только сам факт наличия ключа, а не какое-либо значение при нём.
// ─────────────────────────────────────────────────────────────────────────────

// Set — множество уникальных значений типа T. Это map[T]struct{}: наличие ключа
// означает «элемент в множестве». Значение struct{} памяти не занимает.
type Set[T comparable] map[T]struct{}

// NewSet создаёт ПУСТОЕ, но готовое множество (и сразу кладёт переданные
// значения). Создавать через make ОБЯЗАТЕЛЬНО: нулевое значение Set[T] — это
// nil-карта, и Add на ней ПАНИКует («assignment to entry in nil map»). Has и
// Remove на nil-карте безопасны, но полагаться на это не стоит — заводи
// множество через NewSet.
func NewSet[T comparable](values ...T) Set[T] {
	s := make(Set[T], len(values))
	for _, v := range values {
		s.Add(v)
	}
	return s
}

// Add кладёт значение в множество. Повторный Add того же значения ничего не
// меняет — в этом и смысл множества (уникальность).
//
// Ресивер — ЗНАЧЕНИЕ (s Set[T]), а не указатель: карта в Go уже ссылочный тип,
// копия Set указывает на ту же таблицу, поэтому запись видна и снаружи.
// Указатель понадобился бы, только если бы метод переприсваивал саму карту.
func (s Set[T]) Add(v T) {
	s[v] = struct{}{}
}

// Has отвечает, есть ли значение в множестве. Идиома `_, ok := m[key]` — второй
// результат bool говорит о наличии ключа. Безопасна и на nil-карте (вернёт false).
func (s Set[T]) Has(v T) bool {
	_, ok := s[v]
	return ok
}

// Remove удаляет значение. delete у отсутствующего ключа — не ошибка (no-op) и
// безопасен даже на nil-карте.
func (s Set[T]) Remove(v T) {
	delete(s, v)
}

// Len — размер множества (число уникальных элементов).
func (s Set[T]) Len() int {
	return len(s)
}

// ─────────────────────────────────────────────────────────────────────────────
// Операции над множествами (необязательное расширение из ТЗ). Обе возвращают
// НОВОЕ множество и не меняют исходные.
// ─────────────────────────────────────────────────────────────────────────────

// Union — объединение: всё, что есть хотя бы в одном из множеств.
func (s Set[T]) Union(other Set[T]) Set[T] {
	out := make(Set[T], len(s)+len(other))
	for v := range s {
		out.Add(v)
	}
	for v := range other {
		out.Add(v)
	}
	return out
}

// Intersect — пересечение: то, что есть в обоих множествах сразу.
func (s Set[T]) Intersect(other Set[T]) Set[T] {
	out := make(Set[T])
	for v := range s {
		if other.Has(v) {
			out.Add(v)
		}
	}
	return out
}
