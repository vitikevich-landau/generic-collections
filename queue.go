package main

// ─────────────────────────────────────────────────────────────────────────────
// queue.go — ОЧЕРЕДЬ на дженериках. Очередь живёт по принципу FIFO (first in,
// first out): кто первым встал — тот первым и вышел. Кладём в конец (Enqueue),
// берём с начала (Dequeue). Как очередь в магазине.
//
// Реализация — тот же приём, что и у Stack: параметр типа [T any] и срез внутри.
// Разница только в том, с какого конца снимаем элемент (стек — с конца, очередь
// — с начала).
// ─────────────────────────────────────────────────────────────────────────────

// Queue — очередь значений одного типа T. Нулевое значение сразу рабочее
// (append к nil-срезу), конструктор не нужен.
type Queue[T any] struct {
	items []T
}

// Enqueue добавляет элемент в КОНЕЦ очереди. Ресивер-указатель — метод меняет
// поле items.
func (q *Queue[T]) Enqueue(v T) {
	q.items = append(q.items, v)
}

// Dequeue снимает элемент с НАЧАЛА очереди. Как и Stack.Pop, из пустой очереди
// возвращает (нулевое значение, false), а не панику.
//
// q.items = q.items[1:] сдвигает начало среза на один вперёд. Для учебного
// проекта этого достаточно; в бою на длинной очереди так делать не стоит —
// нижележащий массив не освобождается и память подтекает (берут кольцевой буфер
// или container/list). Здесь важно понять дженерики, а не написать идеальную
// очередь.
func (q *Queue[T]) Dequeue() (T, bool) {
	if len(q.items) == 0 {
		var zero T
		return zero, false
	}
	v := q.items[0]
	q.items = q.items[1:]
	return v, true
}

// Len — длина очереди; «пустая ли» это Len() == 0.
func (q *Queue[T]) Len() int {
	return len(q.items)
}
